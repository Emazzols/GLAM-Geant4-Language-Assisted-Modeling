#pragma once

#include "G4UserRunAction.hh"
#include <map>
#include <string>
#include <vector>

class TFile;
class TTree;

class RunAction : public G4UserRunAction {
public:
    RunAction();
    virtual ~RunAction();

    virtual void BeginOfRunAction(const G4Run*);
    virtual void EndOfRunAction(const G4Run*);

    // Called BEFORE BeginOfRunAction
    void RegisterObservable(const std::string& volumeName);

    // Called at end of each event
    void FillEvent(const std::map<std::string, double>& values);

private:
    TFile* file;
    TTree* tree;

    std::string simName;

    // List of volumes to observe
    std::vector<std::string> fObservables;

    // Branch values (one per volume)
    std::map<std::string, double> fBranchValues;
};


